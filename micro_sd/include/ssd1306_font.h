// Devuelve el índice de fuente para un carácter ASCII (mayúsculas,
// minúsculas, dígitos y símbolos).
static inline uint8_t ssd1306_font_index(char c) {
    if (c >= 'A' && c <= 'Z') return c - 'A' + 1;
    if (c >= 'a' && c <= 'z') return c - 'a' + SSD1306_FONT_a;
    if (c >= '0' && c <= '9') return c - '0' + 27;
    switch (c) {
        case ' ': return SSD1306_FONT_SPACE;
        case '.': return SSD1306_FONT_DOT;
        case '-': return SSD1306_FONT_MINUS;
        case '/': return SSD1306_FONT_SLASH;
        case ':': return SSD1306_FONT_COLON;
        case '@': return SSD1306_FONT_AT;
        case '#': return SSD1306_FONT_HASH;
        case '%': return SSD1306_FONT_PERC;
        case '=': return SSD1306_FONT_EQUAL;
        case '+': return SSD1306_FONT_PLUS;
        case '!': return SSD1306_FONT_BANG;
        case ',': return SSD1306_FONT_COMMA;
        case '?': return SSD1306_FONT_QUEST;
        case '_': return SSD1306_FONT_UNDER;
        default:  return SSD1306_FONT_SPACE;
    }
}

